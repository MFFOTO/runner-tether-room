# -*- coding: utf-8 -*-
"""The sRGB IEC61966-2.1 colour profile, and conversion into it.

Every JPEG Tether Room and Grade Room write carries this profile, so viewers
and the uploader all read the pixels as sRGB (the .cube looks assume it).

The profile is built here rather than shipped as a binary: same colorimetry as
the widely used sRGB IEC61966-2.1 profile (D50-adapted primaries, sRGB curve),
and the same profile description, so tools show "sRGB IEC61966-2.1".
"""

from __future__ import annotations

import io
import struct
from typing import Optional

import numpy as np

ICC_NAME = "sRGB IEC61966-2.1"
_COPYRIGHT = "Generated by Tether Room. sRGB IEC61966-2.1 colorimetry."

try:
    from PIL import Image, ImageCms  # type: ignore
except Exception:                                   # pragma: no cover
    Image = None
    ImageCms = None


def _s15(v: float) -> bytes:
    return struct.pack(">i", int(round(v * 65536.0)))


def _xyz_tag(x: float, y: float, z: float) -> bytes:
    return b"XYZ \x00\x00\x00\x00" + _s15(x) + _s15(y) + _s15(z)


def _desc_tag(text: str) -> bytes:
    a = text.encode("ascii") + b"\x00"
    return (b"desc\x00\x00\x00\x00" + struct.pack(">I", len(a)) + a
            + struct.pack(">I", 0) + struct.pack(">I", 0)       # unicode: none
            + struct.pack(">H", 0) + b"\x00" + b"\x00" * 67)    # scriptcode: none


def _text_tag(text: str) -> bytes:
    return b"text\x00\x00\x00\x00" + text.encode("ascii") + b"\x00"


def _curve_tag(n: int = 1024) -> bytes:
    x = np.linspace(0.0, 1.0, n)
    y = np.where(x <= 0.04045, x / 12.92, ((x + 0.055) / 1.055) ** 2.4)
    vals = np.clip(np.round(y * 65535.0), 0, 65535).astype(">u2")
    return b"curv\x00\x00\x00\x00" + struct.pack(">I", n) + vals.tobytes()


def _build() -> bytes:
    curve = _curve_tag()
    tags = [                                    # D50-adapted sRGB primaries
        (b"desc", _desc_tag(ICC_NAME)),
        (b"cprt", _text_tag(_COPYRIGHT)),
        (b"wtpt", _xyz_tag(0.9642, 1.0, 0.8249)),
        (b"rXYZ", _xyz_tag(0.4361, 0.2225, 0.0139)),
        (b"gXYZ", _xyz_tag(0.3851, 0.7169, 0.0971)),
        (b"bXYZ", _xyz_tag(0.1431, 0.0606, 0.7141)),
        (b"rTRC", curve), (b"gTRC", curve), (b"bTRC", curve),   # one shared body, below
    ]
    table_len = 4 + 12 * len(tags)
    off = 128 + table_len
    table, body, seen = b"", b"", {}
    for sig, data in tags:
        if data in seen:                        # identical tag data is stored once
            o, n = seen[data]
        else:
            o, n = off + len(body), len(data)
            seen[data] = (o, n)
            body += data + b"\x00" * (-len(data) % 4)
        table += sig + struct.pack(">II", o, n)
    size = 128 + table_len + len(body)
    header = (struct.pack(">I", size) + b"\x00\x00\x00\x00"
              + b"\x02\x10\x00\x00" + b"mntr" + b"RGB " + b"XYZ "
              + struct.pack(">6H", 1998, 2, 9, 6, 49, 0)
              + b"acsp" + b"MSFT" + b"\x00\x00\x00\x00"
              + b"IEC " + b"sRGB" + b"\x00" * 8 + b"\x00" * 4
              + _s15(0.9642) + _s15(1.0) + _s15(0.8249)
              + b"\x00\x00\x00\x00").ljust(128, b"\x00")
    return header + struct.pack(">I", len(tags)) + table + body


_PROFILE: Optional[bytes] = None


def srgb_icc() -> bytes:
    """The profile bytes (built once)."""
    global _PROFILE
    if _PROFILE is None:
        _PROFILE = _build()
    return _PROFILE


def is_rgb_profile(icc: bytes) -> bool:
    return len(icc) >= 20 and icc[16:20] == b"RGB "


def to_srgb(img_bgr: np.ndarray, icc: bytes) -> np.ndarray:
    """Convert BGR pixels described by `icc` into sRGB. Raises if it cannot
    (no Pillow, a profile that is not RGB, or an unreadable profile)."""
    if ImageCms is None:
        raise RuntimeError("Pillow is not installed")
    if not is_rgb_profile(icc):
        raise ValueError("not an RGB profile")
    src = ImageCms.ImageCmsProfile(io.BytesIO(icc))
    dst = ImageCms.ImageCmsProfile(io.BytesIO(srgb_icc()))
    tr = ImageCms.buildTransform(
        src, dst, "RGB", "RGB",
        renderingIntent=ImageCms.Intent.RELATIVE_COLORIMETRIC,
        flags=ImageCms.Flags.BLACKPOINTCOMPENSATION)
    im = Image.fromarray(np.ascontiguousarray(img_bgr[:, :, ::-1]))
    ImageCms.applyTransform(im, tr, inPlace=True)
    return np.ascontiguousarray(np.asarray(im)[:, :, ::-1])
